classdef PolarCoding < handle
% Polar Coding Object (PolarCoding)
%
%   Encoding
%       - Unsystematic encoding.
% 
%   Decoding
%       - Successive cancellation (SC) based decoder
%          -> List-SC.
%          -> CRC-List-SC (CRC aided list decoding).
%
%   Author
%       - Bashar Tahir, bashar.tahir@tuwien.ac.at
%         (c) 2020 Institute of Telecommunications, TU Wien.
%         www.nt.tuwien.ac.at 
%
properties
    NrCodeBlocks         % Number of code blocks
    CodeRate             % Code rate
    RateMatching         % The rate matching object
    DecodingAlgorithm    % The decoding algorithm
    ListSize             % List size for List-SC based decoding
    EntireTBCRCPoly      % The CRC polynomial applied to the entire transport block
end

% Class specific properties
properties (SetAccess = private, Hidden = false)
end
 
methods
%%
    function obj = PolarCoding(varargin)
    % Constructs a new PolarCoding object
         if numel(varargin) == 1
              obj.NrCodeBlocks      = varargin{1}.NrCodeBlocks;
              obj.CodeRate          = varargin{1}.CodeRate;
              obj.RateMatching      = varargin{1}.RateMatching;
              obj.DecodingAlgorithm = varargin{1}.DecodingAlgorithm;
              obj.ListSize          = varargin{1}.ListSize;
              if floor(log2(obj.ListSize)) ~= log2(obj.ListSize) || obj.ListSize == 0
                error('The list size for the polar decoder has to be a power of 2 (e.g., 1, 2, 4, 8, etc.).');
              end
              obj.EntireTBCRCPoly   = varargin{1}.CRCPoly;
          else
              error('Number of input variables must be 1');
          end
    end
%%
    function CodedBitsBlock = Encode(varargin)
        % Polar encode the input bits block
        % Uses the Frozen Set generated by the ConstructPolarCode() function.
        %
        % CodedBits = PolarCoding.Encode(Input bits)
        obj       = varargin{1};
        BlockBits = varargin{2};
        Block     = varargin{3};

        % Unsystematic encoding
        n         = Block.Power2Size;
        FrozenSet = Block.FrozenSet;
        
        u = zeros(1, n);
        Kcount = 1;
        for ii = 1:Block.Power2Size
            if FrozenSet(ii) == 0
                u(ii)  = BlockBits(Kcount);
                Kcount = Kcount + 1;
            else
                u(ii) = 0;
            end
        end  
        
        % Fast polar transform
        Fd = [1,0;1,1];
        I = 1:n;
        c = u;
        eS = [1:2:n 2:2:n];
        for ii = 1:log2(n)
            c    = reshape((reshape(c(I)', 2, [])'*Fd)', [], 1)';
            c(I) = c;
            I = I(eS);
        end
        v = mod(c, 2);

        % Apply Rate-Matching
        CodedBitsBlock = obj.RateMatching.RateMatch('Polar', v, 0, 0, Block);           
    end
 %%   
    function DecodedBlockBits = Decode(varargin)
        % Polar decode the input Log-Likelihood Ratios (LLRs) block using the specified Decoding Algorithm
        % Apply the specified Decoding Algorithm and decode each block. 
        % After each block is decoded, CRC is performed and the error
        % detection result is stored in the corresponding Block class.
        %
        % DecodedBits = PolarCoding.Decode(Channel LLRs)
        obj   = varargin{1};  
        Block = varargin{3}; 
        
        INF = 1e10;
        RateDematchedLLRs = obj.RateMatching.RateDematch(varargin{2}, Block); 
       
        channelLLRs = [RateDematchedLLRs  INF*ones(1, Block.Power2Size-Block.CodedBlockSize)];
        
        % Stabilize the calculation of the path metrics by adding a small driving noise to the LLRs
        channelLLRs = channelLLRs + (min(abs(channelLLRs(channelLLRs~=0)))/1000)*(randn(size(channelLLRs))); 
       
        FrozenSet   = Block.FrozenSet;   
        
        switch obj.DecodingAlgorithm
            case 'List-SC'
                ListSz = obj.ListSize;   
                minPM  = Inf;
                
                DecodedBitsL = Coding.ChannelCodingComponents.polarDecodeMEX(channelLLRs, FrozenSet, Block.CodedBlockSize, ListSz);  
                for L = 1:ListSz
                    if DecodedBitsL(1, L) < minPM
                        minPM = DecodedBitsL(1, L);
                        minL  = L;
                    end
                end
                DecodedBits = DecodedBitsL(2:end, minL);
                DecodedBits = DecodedBits(FrozenSet == 0);
                if obj.NrCodeBlocks  ~= 1
                    % Subblock CRC
                    Block.CRCDetectionResult = Coding.ChannelCodingComponents.CRC.Detect(DecodedBits.', '24B');
                else
                    % Tranmission consists of only a single block, this one
                    Block.CRCDetectionResult = Coding.ChannelCodingComponents.CRC.Detect(DecodedBits.', obj.EntireTBCRCPoly);
                end 
                
            case 'CRC-List-SC'
                ListSz = obj.ListSize;  
                minPM  = Inf;
                
                DecodedBitsL = Coding.ChannelCodingComponents.polarDecodeMEX(channelLLRs, FrozenSet, Block.CodedBlockSize, ListSz);    
                for L = 1:ListSz
                    temp = DecodedBitsL(2:end, L);
                    temp = temp(FrozenSet == 0);
                    
                    if obj.NrCodeBlocks  ~= 1
                        % Subblock CRC
                        Block.CRCDetectionResult = Coding.ChannelCodingComponents.CRC.Detect(temp.', '24B');
                    else
                        % Tranmission consists of only a single block, this one
                        Block.CRCDetectionResult = Coding.ChannelCodingComponents.CRC.Detect(temp.', obj.EntireTBCRCPoly);
                    end 

                    if Block.CRCDetectionResult == 0
                        minL = L;
                        break;
                    end
                end
                
                % If no path passes the CRC, then choose the path with lowest path metric and hope for fewest bit errors
                if Block.CRCDetectionResult == 1
                    for L = 1:ListSz
                        if DecodedBitsL(1, L) < minPM
                            minPM = DecodedBitsL(1, L);
                            minL  = L;
                        end
                    end
                end
                
                DecodedBits = DecodedBitsL(2:end, minL);
                DecodedBits = DecodedBits(FrozenSet == 0);
            otherwise
                error('The decoding algorithm is not supported.');
        end
        DecodedBlockBits = DecodedBits.';
        
        % Subblock CRC calculation
        if obj.NrCodeBlocks  ~= 1
            DecodedBlockBits = DecodedBlockBits(1:Block.InputBlockSize-24);
        else
            DecodedBlockBits = DecodedBlockBits(1:Block.InputBlockSize);
        end 
    end
end
 %%
methods(Static)
    function ConstructPolarCode(varargin)
        % Construct a new Polar code.
        
        obj = varargin{1};
        
        % Automatically select TargetSNR based on prior simulations
        [~, ed] = min(abs(obj.CodeRate - [1/5, 1/3, 1/2, 2/3, 5/6, 13/14]).^2);
        switch ed
            case 1
                TargetSNR = 0.61;
            case 2
                TargetSNR = 1.42;
            case 3
                TargetSNR = 4.68;
            case 4
                TargetSNR = 5.00;
            case 5
                TargetSNR = 7.00;
            case 6
                TargetSNR = 8.83;
        end
        % Custom TargetSNR
%         TargetSNR = ?;

        for CBi = 1:obj.NrCodeBlocks
            Block = obj.Blocks(CBi);
            k = Block.InputBlockSize;
            Block.CodedBlockSize = Block.MatchedLength;
            % Code rate selection
            n = 2^nextpow2(Block.CodedBlockSize);      
            nt = Block.CodedBlockSize;
            Block.Power2Size = n;
            Block.FrozenSet = ConstructPolarCodeAlgo();  
        end   

        function FrozenSet = ConstructPolarCodeAlgo()
            % Find the frozen set according to http://ieeexplore.ieee.org/document/7998250/ .
            log2n = log2(n);
            P = zeros(n, 1);
            SNR = 10^(TargetSNR/10);
            P(1) = erfc(sqrt(SNR./2))./2;
            for i = 1:log2n
                j = 2^(i-1);
                kz = 1:j;
                p = P(kz);
                P(kz) = 2.*p.*(1-p);
                P(kz+j) = erfc(sqrt(2).*erfcinv(2*p))./2;
            end
            P = Utils.Extras.bitrevorder(P);
            P(nt+1:end) = 1;
            [~,I] = sort(P,'descend');
            
            FrozenSet = zeros(1,n);
            FrozenSet(I(1:(n-k))) = 1; 
        end  
end
      
end

